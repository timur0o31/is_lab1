package ru.itmo.tim.requestDto;

public class LocationRequestDto {
    private Integer x;
    private Integer y;
    private Long z;
    public LocationRequestDto(){

    }


    public int getX() {
        return x;
    }

    public void setX(int x) {
        this.x = x;
    }

    public int getY() {
        return y;
    }

    public void setY(int y) {
        this.y = y;
    }

    public long getZ() {
        return z;
    }

    public void setZ(long z) {
        this.z = z;
    }
}
